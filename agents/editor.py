"""ScamShield Editor: build a captioned 59-second vertical reel with FFmpeg.

Run from the project root: python -m agents.editor
Requires: Pillow and FFmpeg/FFprobe available on PATH.
"""

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "outputs"
IMAGES = ROOT / "assets" / "images"
AUDIO = ROOT / "assets" / "audio"
FPS = 25
SIZE = (1080, 1920)


def run(args):
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(
            f"Command failed ({result.returncode}): {' '.join(map(str, args))}\n"
            f"{result.stderr[-2500:]}"
        )
    return result.stdout.strip()


def probe_duration(path):
    return float(run([
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1", str(path)
    ]))


def audio_for_scene(scene_id):
    # Prefer the names generated by a scene-per-clip Narrator.
    patterns = [
        f"scene_{scene_id:02d}.mp3", f"scene_{scene_id:02d}.wav",
        f"scene_{scene_id:02d}.m4a", f"scene_{scene_id}.mp3",
        f"scene_{scene_id}.wav", f"scene_{scene_id}.m4a",
        f"scene_{scene_id:02d}_*.mp3", f"scene_{scene_id:02d}_*.wav",
        f"scene_{scene_id:02d}_*.m4a", f"scene_{scene_id}_*.mp3",
    ]
    for pattern in patterns:
        matches = sorted(AUDIO.glob(pattern))
        if matches:
            return matches[0]
    return None


def get_font(size):
    candidates = [
        "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "/System/Library/Fonts/SFNS.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    ]
    for p in candidates:
        try:
            return ImageFont.truetype(p, size)
        except OSError:
            pass
    return ImageFont.load_default()


def wrap_text(text, font, draw, max_width):
    words = text.split()
    lines, current = [], ""
    for word in words:
        trial = (current + " " + word).strip()
        if draw.textbbox((0, 0), trial, font=font)[2] <= max_width:
            current = trial
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def caption_image(source, destination, narration, end_card=False):
    with Image.open(source) as image:
        image = image.convert("RGB")
        if image.size != SIZE:
            image = image.resize(SIZE, Image.Resampling.LANCZOS)
        if narration.strip() and not end_card:
            overlay = Image.new("RGBA", SIZE, (0, 0, 0, 0))
            d = ImageDraw.Draw(overlay)
            # Dedicated subtitle lane: content artwork stays above y=1400.
            # Full spoken captions remain verbatim and readable at 1080px width.
            font_size = 48
            while True:
                font = get_font(font_size)
                lines = wrap_text(narration, font, d, 956)
                if len(lines) <= 4 or font_size <= 36:
                    break
                font_size -= 2
            if len(lines) > 4:
                raise ValueError("Narration caption too long for safe subtitle lane")
            line_h = 51
            top, bottom = 1400, 1620
            d.rounded_rectangle((42, top, 1038, bottom), radius=20, fill=(5, 15, 32, 238))
            y = top + (bottom - top - len(lines) * line_h) / 2 + 2
            for line in lines:
                bbox = d.textbbox((0, 0), line, font=font)
                width = bbox[2] - bbox[0]
                d.text((540 - width / 2, y), line, font=font, fill=(255, 255, 255, 255))
                y += line_h
            image = Image.alpha_composite(image.convert("RGBA"), overlay).convert("RGB")
        image.save(destination, quality=94)


def srt_stamp(seconds):
    ms = int(round(seconds * 1000))
    h, rem = divmod(ms, 3600000)
    m, rem = divmod(rem, 60000)
    s, ms = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def build():
    if not shutil.which("ffmpeg") or not shutil.which("ffprobe"):
        raise RuntimeError("FFmpeg and FFprobe must be installed and on PATH.")
    script = json.loads((OUTPUTS / "script.json").read_text(encoding="utf-8"))
    scenes = script["scenes"]
    if len(scenes) != 7 or scenes[0]["start_s"] != 0 or scenes[-1]["end_s"] != 59:
        raise ValueError("Expected the approved seven-scene, 59-second script.")
    if any(a["end_s"] != b["start_s"] for a, b in zip(scenes, scenes[1:])):
        raise ValueError("Scene timeline contains a gap or overlap.")

    caption_entries = []
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="scamshield_editor_") as work:
        temp = Path(work)
        segments = []
        for scene in scenes:
            i = scene["scene_id"]
            slot = float(scene["end_s"] - scene["start_s"])
            if slot <= 0:
                raise ValueError(f"Nonpositive scene duration: {i}")
            img = IMAGES / f"scene_{i:02d}.png"
            if not img.exists():
                raise FileNotFoundError(f"Missing scene image: {img}")
            narration = scene.get("voiceover", "").strip()
            audio = audio_for_scene(i)
            if narration and audio is None:
                raise FileNotFoundError(f"Audio missing for scene {i}; found no scene_{i:02d}*.mp3/wav/m4a in {AUDIO}")
            if narration and probe_duration(audio) > slot + 0.05:
                raise ValueError(f"Scene {i} narration exceeds slot; rerun Narrator/check report")
            image_path = temp / f"captioned_{i:02d}.png"
            caption_image(img, image_path, narration, end_card=(i == 7))
            segment = temp / f"segment_{i:02d}.mp4"
            video_args = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-loop", "1", "-framerate", str(FPS), "-i", str(image_path)]
            if narration:
                video_args += ["-i", str(audio), "-filter_complex", "[1:a]aresample=48000,apad[a]", "-map", "0:v", "-map", "[a]"]
            else:
                video_args += ["-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo", "-map", "0:v", "-map", "1:a"]
            video_args += [
                "-t", f"{slot:.3f}", "-r", str(FPS), "-c:v", "libx264", "-preset", "veryfast",
                "-crf", "22", "-pix_fmt", "yuv420p", "-c:a", "aac", "-ar", "48000",
                "-ac", "2", "-b:a", "160k", "-movflags", "+faststart", str(segment)
            ]
            run(video_args)
            segments.append(segment)
            if narration:
                caption_entries.append((scene["start_s"], scene["end_s"], narration))
            print(f"Scene {i:02d} rendered: {slot:g}s")
        list_path = temp / "concat.txt"
        list_path.write_text("".join(f"file '{p.as_posix()}'\n" for p in segments), encoding="utf-8")
        final = OUTPUTS / "scamshield_third_cut_layout_fixed.mp4"
        run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(list_path), "-c", "copy", "-movflags", "+faststart", str(final)])

    srt = OUTPUTS / "scamshield_third_cut_layout_fixed.srt"
    srt.write_text("\n\n".join(
        f"{n}\n{srt_stamp(a)} --> {srt_stamp(b)}\n{text}"
        for n, (a, b, text) in enumerate(caption_entries, 1)
    ) + "\n", encoding="utf-8")
    actual = probe_duration(final)
    print(f"Video: {final}")
    print(f"Subtitles: {srt}")
    print(f"Final duration: {actual:.2f}s (target 59s)")
    if abs(actual - 59) > 0.35:
        raise RuntimeError(f"Exported duration unexpectedly differs from 59s: {actual:.2f}s")
    print("Status: THIRD CUT — review visuals, audio, factual claims and disclosure before final submission")


if __name__ == "__main__":
    build()
